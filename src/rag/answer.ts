/**
 * Правило відмови: бал RRF НЕ поріг (він залежить лише від рангів). Міряємо подібність:
 * косинус найкращого фрагмента (embeddinggemma-2:270m). Відкалібровано на еталонному
 * наборі (`npx tsx scripts/search.ts --golden`, 31.10.2026): unanswerable — 0,7319…0,7609,
 * з відповіддю — від 0,7707. Поріг посередині проміжку; запас лише ~0,005 з кожного боку —
 * див. docs/lab2/retrieval.md, розділ 4.
 */
export const REFUSE_BELOW_COSINE = 0.765;

export const REFUSAL_TEXT = 'У документах колекції цього немає.';

/**
 * bestCosine — косинус ПЕРШОГО фрагмента векторної гілки (до злиття), тобто те саме число,
 * на якому відкалібровано поріг (`--golden`, колонка «топ-косинус»). Не максимум серед топ-5
 * після RRF: найближчий за змістом фрагмент може не потрапити в топ-5 злиття.
 */
export function shouldRefuse(bestCosine: number | undefined, threshold = REFUSE_BELOW_COSINE): boolean {
  return (bestCosine ?? -1) < threshold;
}

