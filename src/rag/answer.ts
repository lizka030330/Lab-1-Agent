export function buildUserMessage(query: string, context: string): string {
  return `Фрагменти документів:\n\n${context}\n\n===\nЗапит користувача: ${query}`;
}

export function isRefusal(answer: string): boolean {
  return answer.includes(REFUSAL_TEXT) || /у документах (колекції )?(цього|такого) немає/i.test(answer);
}
